/**
 * ASSET MANIFEST
 * --------------
 * Every image/audio file the film uses, in storyboard order.
 * To replace an image: put the new file in public/assets/ with the same name
 * (or change `src` here), update `w`/`h`, then run `npm run prepare-assets`.
 * Focal points used by the scenes are in image pixels, so if a replacement
 * photo is framed differently, adjust the `focus` values in the scene file.
 *
 * `kind` documents provenance:
 *   "photo"          – original photograph supplied by the owner
 *   "reconstruction" – AI-generated conceptual reconstruction (NOT literal
 *                      historical footage; the film labels these on screen)
 *   "logo"           – supplied brand artwork, used unaltered
 *   "standin"        – placeholder until the owner supplies the real file
 */
export type Asset = {
  src: string;
  w: number;
  h: number;
  kind: "photo" | "reconstruction" | "logo" | "standin";
  note: string;
};

